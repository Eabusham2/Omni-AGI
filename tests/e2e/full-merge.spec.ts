import { _electron as electron, expect, test } from "@playwright/test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

test("complete merge review reaches typed transport and renders pause/resume/stop receipts across themes", async () => {
  const root = await mkdtemp(join(tmpdir(), "omni-merge-ui-"));
  const env = Object.fromEntries(Object.entries(process.env).filter(([name, value]) => name !== "ELECTRON_RUN_AS_NODE" && value !== undefined)) as Record<string, string>;
  const application = await electron.launch({ args: [resolve("tests/e2e/full-merge-main.cjs")], env: { ...env, OMNI_MERGE_UI_DATA: root, OMNI_MERGE_UI_REPO: process.cwd() } });
  try {
    const page = await application.firstWindow();
    const failures: string[] = []; page.on("pageerror", (error) => failures.push(error.message));
    await page.getByRole("button", { name: "Review a new merge" }).click();
    await page.getByLabel("Aster", { exact: true }).check(); await page.getByLabel("Lumen", { exact: true }).check();
    await page.getByLabel("Name", { exact: true }).fill("Connected fixture");
    await page.getByLabel("System shell", { exact: true }).selectOption("ask");
    await page.getByRole("button", { name: "Choose destination spill drives…" }).click();
    await expect(page.getByText("/fixture/selected-drive", { exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Create merged instance" })).toBeDisabled();
    await page.screenshot({ path: test.info().outputPath("merge-review-dark.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => { document.documentElement.dataset.colorScheme = "light"; });
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0);
    await page.getByText("All settings — complete JSON review", { exact: true }).click();
    await expect(page.getByLabel("Destination configuration")).toBeVisible();
    const json = page.getByLabel("Destination configuration");
    const validSettings = await json.inputValue();
    await json.fill("{ not JSON"); await page.getByRole("button", { name: "Apply edited JSON" }).click();
    await expect(page.getByRole("alert")).toBeVisible();
    await json.fill(validSettings); await page.getByRole("button", { name: "Apply edited JSON" }).click();
    await page.getByLabel("I reviewed the new instance's settings and access policy.", { exact: false }).check();
    await page.screenshot({ path: test.info().outputPath("merge-review-light-narrow.png"), fullPage: true });
    await page.getByRole("button", { name: "Create merged instance" }).click();
    await expect(page.getByText("Copying complete snapshots", { exact: true })).toBeVisible();
    const submitted = await page.evaluate(() => (window as unknown as { __fullMergeRequests: Array<Record<string, any>> }).__fullMergeRequests[0]!);
    expect(submitted.parentIds).toEqual(["parent-0", "parent-1"]); expect(submitted.accessPolicy.credentials).toBe("none");
    expect(submitted.accessPolicy.mcp).toBe("disabled"); expect(submitted.accessPolicy.toolPermissions.find((value: any) => value.toolId === "system.shell").level).toBe("ask");
    expect(submitted.spillPoolSelectionId).toBe("fixture-native-picker");
    expect(submitted.config.deviceResources.storageDirectories).toEqual(["/fixture/selected-drive"]);
    await expect(page.getByText("fixture-native-picker", { exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: "Pause", exact: true }).click();
    await expect(page.getByRole("button", { name: "Resume same merge" })).toBeEnabled();
    await page.getByRole("button", { name: "Stop & discard…" }).hover();
    expect(await page.getByRole("button", { name: "Stop & discard…" }).evaluate((element) => getComputedStyle(element).color)).not.toBe("rgb(255, 255, 255)");
    await page.screenshot({ path: test.info().outputPath("merge-paused.png"), fullPage: true });
    await page.getByRole("button", { name: "Resume same merge" }).click();
    await expect(page.getByRole("button", { name: "Open merged instance" })).toBeVisible();
    await expect(page.getByTestId("parent-count")).toHaveText("2 original parents preserved · 3 library instances");
    await page.reload(); await expect(page.getByRole("button", { name: "Open merged instance" })).toBeVisible();
    await page.getByRole("button", { name: "Review a new merge" }).click();
    await page.getByLabel("Aster", { exact: true }).check(); await page.getByLabel("Lumen", { exact: true }).check();
    await page.getByLabel("Name", { exact: true }).fill("Discarded fixture");
    await page.getByLabel("I reviewed the new instance's settings and access policy.", { exact: false }).check();
    await page.getByRole("button", { name: "Create merged instance" }).click();
    await page.getByRole("button", { name: "Stop & discard…" }).click();
    await page.getByRole("button", { name: "Discard incomplete output" }).click();
    await expect(page.getByText("Stopped — incomplete output removed", { exact: true })).toBeVisible();
    await expect(page.getByTestId("parent-count")).toHaveText("2 original parents preserved · 3 library instances");
    await page.screenshot({ path: test.info().outputPath("merge-stopped.png"), fullPage: true });
    expect(failures).toEqual([]);
  } finally { await application.close(); await rm(root, { recursive: true, force: true }); }
});
