@dataclass(frozen=True)
class GeneratedAnswerEvidence:
    """Measurements from one real post-restart chat, not sequence decoding."""

    expected_text: str
    generated_text: str
    backend: str
    generated_token_count: int
    answer_quality_passed: bool
    fresh_attention_committed: bool
    fresh_attention_epoch: int
    worker_restarted: bool
    cortical_checksum_before_learning: str
    cortical_checksum_after_learning: str
    cortical_checksum_after_restart: str
    training_steps_before: int
    training_steps_after: int
    raw_text_retrieved: bool
    raw_token_ids_retrieved: bool


@dataclass(frozen=True)
class PathObservation:
    path: MemoryPath
    representation: Representation
    segment_count: int
    query_contains_learned_cue: bool
    typed_target_present: bool
    attributable_source: bool
    accepted_for_learning: bool
    coverage_complete: Optional[bool]
    grammar_specific_gate_used: bool
    statistical_updates: int
    semantic_target_present: bool
    semantic_target_score: float
    semantic_control_score: float
    statistical_forward_precision: str
    recent_dialogue_tokens: int
    prior_prompt_text_expanded: bool
    raw_source_text_injected: bool
    exact_eligible_segments: int = 0
    answer: Optional[GeneratedAnswerEvidence] = None


@dataclass(frozen=True)
class AcceptanceResult:
    path: MemoryPath
    expected_level: Literal["exact-generated", "semantic-generated"]
    passed: bool
    failures: Tuple[str, ...]


def expected_acceptance_level(
    observation: PathObservation,
) -> Literal["exact-generated", "semantic-generated"]:
    spec = PATH_SPECS[observation.path]
    if observation.representation != "detailed":
        return "semantic-generated"
    if not observation.query_contains_learned_cue:
        return "semantic-generated"
    if spec.exact_mode == "typed-target":
        return (
            "exact-generated"
            if observation.typed_target_present
            else "semantic-generated"
        )
    return (
        "exact-generated"
        if observation.exact_eligible_segments > 0
        else "semantic-generated"
    )


def assess_path_observation(observation: PathObservation) -> AcceptanceResult:
    """Check necessary evidence; a synthetic matrix pass is not a live pass."""

    spec = PATH_SPECS[observation.path]
    level = expected_acceptance_level(observation)
    failures = []

    if not observation.attributable_source:
        failures.append("learning source is not attributable")
    if not observation.accepted_for_learning:
        failures.append("source was quarantined, rejected, or otherwise not learned")
    if spec.coverage_required and observation.coverage_complete is not True:
        failures.append("source traversal/record coverage is incomplete")
    if observation.grammar_specific_gate_used:
        failures.append("a grammar-specific fact gate selected the memory path")
    if observation.statistical_updates < 1:
        failures.append("the generic statistical association stage did not update")
    if not observation.semantic_target_present:
        failures.append("the learned semantic target was not retrieved")
    if not (
        math.isfinite(observation.semantic_target_score)
        and math.isfinite(observation.semantic_control_score)
        and observation.semantic_target_score > observation.semantic_control_score
    ):
        failures.append("semantic target did not outrank the unrelated control")
    if observation.statistical_forward_precision != "exact ternary {-1,0,+1}":
        failures.append("statistical recall did not use exact ternary forwards")

    # The current query is allowed. Prior conversation/source prose is not.
    if observation.recent_dialogue_tokens != 0:
        failures.append("prior recent-dialogue context was still present")
    if observation.prior_prompt_text_expanded:
        failures.append("prior prompt text was expanded into the query")
    if observation.raw_source_text_injected:
        failures.append("raw source text was injected during recall")

    answer = observation.answer
    if answer is None:
        failures.append("no model-generated answer after Fresh and worker restart")
    else:
        if not answer.fresh_attention_committed or answer.fresh_attention_epoch < 1:
            failures.append("Fresh attention did not commit before the answer")
        if not answer.worker_restarted:
            failures.append("answer was not generated after a worker restart")
        if answer.backend != "mutable-omni-decoder":
            failures.append("answer did not come from a model generation backend")
        if answer.generated_token_count < 1 or not answer.generated_text.strip():
            failures.append("model produced no answer tokens")
        checksums = (
            answer.cortical_checksum_before_learning,
            answer.cortical_checksum_after_learning,
            answer.cortical_checksum_after_restart,
        )
        if not all(re.fullmatch(r"[0-9a-f]{64}", value) for value in checksums):
            failures.append("cortical weight checksums are missing or invalid")
        elif (
            answer.cortical_checksum_before_learning
            == answer.cortical_checksum_after_learning
        ):
            failures.append("learning did not change cortical weights")
        elif (
            answer.cortical_checksum_after_learning
            != answer.cortical_checksum_after_restart
        ):
            failures.append("learned cortical weights did not survive restart")
        if answer.training_steps_after <= answer.training_steps_before:
            failures.append("no cortical training step was committed")
        if answer.raw_text_retrieved or answer.raw_token_ids_retrieved:
            failures.append("answer consulted retained text or raw token ids")
        if not answer.answer_quality_passed:
            failures.append("generated answer failed its answer-quality check")
        if level == "exact-generated" and (
            not answer.expected_text
            or answer.generated_text != answer.expected_text
        ):
            failures.append("generated response was not an exact content match")

    return AcceptanceResult(
        path=observation.path,
        expected_level=level,
        passed=not failures,
        failures=tuple(failures),
    )


