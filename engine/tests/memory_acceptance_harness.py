"""No-context, model-generated acceptance rules for multi-stage memory.

This is a test harness, not another memory implementation.  Focused path tests
feed it measurements from the real brain after the protected integration is
complete. Exact sequence decoding can establish a memory mechanism, but cannot
stand in for an answer generated by learned cortical weights after restart.
"""

from __future__ import annotations

